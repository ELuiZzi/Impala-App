import assert from 'node:assert/strict';
import { test } from 'node:test';
import { createInnertube, musicMetadata } from '../src/innertube.js';

const DESC = 'Provided to YouTube by Universal Music Group\n\nLet It Happen · Tame Impala\n\nCurrents\n\n℗ 2015 Modular Recordings\n\nReleased on: 2015-07-17\n\nAuto-generated by YouTube.';

test('musicMetadata: pista, artistas, álbum y año de una pista de YouTube Music', () => {
  assert.deepEqual(musicMetadata(DESC), { track: 'Let It Happen', artists: ['Tame Impala'], artist: 'Tame Impala', album: 'Currents', release_year: 2015 });
  assert.deepEqual(musicMetadata('Video oficial de Tame Impala'), {});
});

test('info: una petición al reproductor con el cliente de yt-dlp y formato de yt-dlp', async () => {
  const requests = [];
  const fetchImpl = async (url, init) => {
    const body = JSON.parse(init.body);
    requests.push({ url, body, headers: init.headers });
    if (url.includes('visitor_id')) return Response.json({ responseContext: { visitorData: 'VD' } });
    return Response.json({
      playabilityStatus: { status: 'OK' },
      videoDetails: { videoId: 'mmmmmmmmmmm', title: 'Let It Happen', author: 'Tame Impala - Topic', lengthSeconds: '468', shortDescription: DESC, thumbnail: { thumbnails: [{ url: 'https://i.ytimg.com/vi/m/hq.jpg?x=1', width: 480, height: 360 }] } },
      streamingData: {
        adaptiveFormats: [
          { itag: 251, url: 'https://gv/251', mimeType: 'audio/webm; codecs="opus"', bitrate: 140000, contentLength: '7000000' },
          { itag: 140, url: 'https://gv/140', mimeType: 'audio/mp4; codecs="mp4a.40.2"', bitrate: 130000 },
          { itag: 137, url: 'https://gv/137', mimeType: 'video/mp4; codecs="avc1"' },
          { itag: 250, signatureCipher: 's=x', mimeType: 'audio/webm; codecs="opus"' },
        ],
      },
    });
  };
  const client = { name: 'VISIONOS', id: 101, version: '1.02', userAgent: 'UA-vision', context: { osName: 'visionOS' } };
  const it = createInnertube({ fetchImpl, clientFor: async () => client });
  const info = await it.info('mmmmmmmmmmm');
  assert.deepEqual(info.formats.map((f) => [f.format_id, f.acodec, f.ext]), [['251', 'opus', 'webm'], ['140', 'mp4a.40.2', 'm4a']]);
  assert.equal(info.formats[0].http_headers['User-Agent'], 'UA-vision');
  assert.equal(info.formats[0].downloader_options.http_chunk_size, 10 * 1024 * 1024);
  assert.equal(info.duration, 468);
  assert.equal(info.album, 'Currents');
  assert.equal(info.thumbnails.at(-1).url, 'https://i.ytimg.com/vi_webp/mmmmmmmmmmm/maxresdefault.webp', 'la mejor, en WebP (se recorta al convertirla)');
  const player = requests.find((r) => r.url.includes('/player'));
  assert.equal(player.body.context.client.clientName, 'VISIONOS');
  assert.equal(player.body.context.client.visitorData, 'VD');
  assert.equal((await it.audioStream('mmmmmmmmmmm')).url, 'https://gv/140');
});

test('info: sin audio directo o video no disponible → error (quien llama vuelve a yt-dlp)', async () => {
  const fetchImpl = async (url) =>
    url.includes('visitor_id') ? Response.json({ responseContext: { visitorData: 'VD' } }) : Response.json({ playabilityStatus: { status: 'ERROR', reason: 'Video unavailable' } });
  await assert.rejects(createInnertube({ fetchImpl }).info('xxxxxxxxxxx'), /Video unavailable/);
});
